create or replace function public.english_get_learning_route_overview()
returns jsonb language sql stable security definer
set search_path=pg_catalog,public,english,auth as $$
with uid as (select auth.uid() id), ft as (
 select r.*,(r.fast_track_status='ready' or (r.fast_track_status='waiting' and r.next_fast_track_check<=now())) ready_now
 from english.learning_route_state r cross join uid where r.user_id=uid.id and r.route='fast_track'
), origins as (
 select o,count(*)::int total,count(*) filter(where f.fast_track_status='mastered')::int mastered,
   count(*) filter(where f.fast_track_status<>'mastered')::int remaining
 from ft f cross join lateral unnest(f.origins) o group by o
), starhist as (
 select count(distinct question_id) filter(where to_route='fast_track' and origin='From Starred')::int moved_fast,
        count(distinct question_id) filter(where to_route='targeted' and origin='From Starred')::int moved_targeted
 from english.learning_route_events e cross join uid where e.user_id=uid.id
), saved as (
 select distinct si.practice_question_id question_id from english.saved_items si cross join uid where si.user_id=uid.id and si.active and nullif(btrim(si.practice_question_id),'') is not null
), savestats as (
 select count(*)::int total,
  count(*) filter(where r.route='fast_track')::int fast_track,
  count(*) filter(where r.route='fast_track' and r.fast_track_status='mastered')::int fast_mastered,
  count(*) filter(where r.route='fast_track' and r.fast_track_status<>'mastered')::int fast_remaining,
  count(*) filter(where r.route='targeted')::int targeted,
  count(*) filter(where r.route is null or r.route in ('unclassified','starred_unresolved'))::int unclassified
 from saved s left join english.learning_route_state r on r.user_id=(select id from uid) and r.question_id=s.question_id
), savedhist as (
 select count(distinct e.question_id) filter(where e.to_route='targeted')::int ever_targeted,
        count(distinct e.question_id) filter(where e.to_route='targeted' and exists(select 1 from english.learning_route_state r where r.user_id=e.user_id and r.question_id=e.question_id and r.route<>'targeted'))::int recovered
 from english.learning_route_events e join saved s on s.question_id=e.question_id cross join uid where e.user_id=uid.id
), active_star as (select count(*)::int n from english.question_state s cross join uid where s.user_id=uid.id and s.last_marked and not s.mastered)
select case when (select id from uid) is null then jsonb_build_object('ok',false,'error','Authentication required') else jsonb_build_object(
 'ok',true,
 'fastTrack',jsonb_build_object(
   'total',(select count(*) from ft),'readyToVerify',(select count(*) from ft where ready_now and fast_track_status<>'mastered'),
   'waiting',(select count(*) from ft where fast_track_status='waiting' and not ready_now),'mastered',(select count(*) from ft where fast_track_status='mastered'),
   'remaining',(select count(*) from ft where fast_track_status<>'mastered'),
   'origins',coalesce((select jsonb_agg(jsonb_build_object('origin',o,'total',total,'mastered',mastered,'remaining',remaining) order by o) from origins),'[]'::jsonb)
 ),
 'starred',jsonb_build_object('active',(select n from active_star),'movedFastTrack',sh.moved_fast,'movedTargeted',sh.moved_targeted,
   'fastTrackMastered',(select count(*) from ft where 'From Starred'=any(origins) and fast_track_status='mastered'),
   'fastTrackRemaining',(select count(*) from ft where 'From Starred'=any(origins) and fast_track_status<>'mastered')),
 'saved',jsonb_build_object('total',ss.total,'fastTrack',ss.fast_track,'fastTrackMastered',ss.fast_mastered,'fastTrackRemaining',ss.fast_remaining,
   'targeted',ss.targeted,'everTargeted',coalesce(sh2.ever_targeted,0),'recoveredStable',coalesce(sh2.recovered,0),'stillLearning',ss.targeted,'unclassified',ss.unclassified)
) end
from starhist sh cross join savestats ss cross join savedhist sh2;
$$;

create or replace function public.english_get_fast_track_batch(p_count integer default 30,p_origin text default null)
returns jsonb language sql stable security definer
set search_path=pg_catalog,public,english,auth as $$
with r as (
 select x.*,case when x.fast_track_status='ready' then 0 else 1 end wait_ord
 from english.learning_route_state x
 where x.user_id=auth.uid() and x.route='fast_track' and x.fast_track_status<>'mastered'
   and (x.fast_track_status='ready' or x.next_fast_track_check<=now())
   and (p_origin is null or p_origin=any(x.origins))
   and nullif(english.route_targeted_reason(auth.uid(),x.question_id),'') is null
 order by wait_ord,x.next_fast_track_check nulls first,x.updated_at,x.question_id
 limit greatest(1,least(100,coalesce(p_count,30)))
)
select coalesce(jsonb_agg(english.question_payload(auth.uid(),r.question_id)||jsonb_build_object(
 'fastTrack',true,'fastTrackStatus',r.fast_track_status,'fastTrackOrigins',r.origins,'fastTrackReason',r.last_route_reason,
 'fastTrackNextCheck',r.next_fast_track_check,'fastTrackFailureDecision',r.pending_failure_decision
) order by r.wait_ord,r.next_fast_track_check nulls first,r.question_id),'[]'::jsonb) from r;
$$;

create or replace function public.english_get_fast_track_items(p_origin text default null,p_status text default 'all',p_limit integer default 100,p_offset integer default 0)
returns jsonb language sql stable security definer
set search_path=pg_catalog,public,english,auth as $$
with r as (
 select x.* from english.learning_route_state x where x.user_id=auth.uid() and x.route='fast_track'
  and (p_origin is null or p_origin=any(x.origins))
  and (lower(coalesce(p_status,'all'))='all' or (lower(p_status)='mastered' and x.fast_track_status='mastered') or (lower(p_status)='remaining' and x.fast_track_status<>'mastered'))
 order by case x.fast_track_status when 'ready' then 1 when 'waiting' then 2 else 3 end,x.updated_at desc,x.question_id
 limit greatest(1,least(250,coalesce(p_limit,100))) offset greatest(0,coalesce(p_offset,0))
)
select coalesce(jsonb_agg(english.question_payload(auth.uid(),r.question_id)||jsonb_build_object(
 'fastTrackStatus',r.fast_track_status,'fastTrackOrigins',r.origins,'fastTrackReason',r.last_route_reason,'fastTrackEnteredAt',r.entered_fast_track_at,
 'fastTrackNextCheck',r.next_fast_track_check,'fastTrackMasteredAt',r.fast_track_mastered_at,'routeHistory',coalesce((select jsonb_agg(jsonb_build_object('at',e.event_at,'type',e.event_type,'from',e.from_route,'to',e.to_route,'origin',e.origin,'reason',e.reason) order by e.event_at) from english.learning_route_events e where e.user_id=r.user_id and e.question_id=r.question_id),'[]'::jsonb)
) order by case r.fast_track_status when 'ready' then 1 when 'waiting' then 2 else 3 end,r.updated_at desc),'[]'::jsonb) from r;
$$;

create or replace function public.english_set_fast_track(p_question_id text,p_fast_track boolean default true)
returns jsonb language plpgsql security definer
set search_path=pg_catalog,public,english,auth as $$
declare uid uuid:=auth.uid(); r english.learning_route_state%rowtype; reason text;
begin
 if uid is null then raise exception 'Authentication required'; end if;
 if not exists(select 1 from english.questions q where q.question_id=btrim(p_question_id) and q.active) then raise exception 'Question not found'; end if;
 if coalesce(p_fast_track,true) then
   reason:=english.route_targeted_reason(uid,btrim(p_question_id));
   if nullif(reason,'') is not null then return jsonb_build_object('ok',false,'reason',reason,'route','targeted'); end if;
   return english.route_to_fast_track(uid,btrim(p_question_id),'Manual Fast Track','Learner requested cheap verification',false);
 end if;
 select * into r from english.learning_route_state where user_id=uid and question_id=btrim(p_question_id);
 if found and r.route='fast_track' then
   update english.learning_route_state set route='unclassified',fast_track_status=null,next_fast_track_check=null,pending_failure_decision=false,last_route_reason='Removed from Fast Track',updated_at=now() where user_id=uid and question_id=btrim(p_question_id);
   perform english.route_event(uid,btrim(p_question_id),'UNROUTE','fast_track','unclassified','Manual Fast Track','Learner removed Fast Track','{}'::jsonb,null);
 end if;
 return jsonb_build_object('ok',true,'route','unclassified');
end $$;

create or replace function public.english_resolve_fast_track_failure(p_question_id text,p_add_targeted boolean)
returns jsonb language plpgsql security definer
set search_path=pg_catalog,public,english,auth as $$
declare uid uuid:=auth.uid(); r english.learning_route_state%rowtype;
begin
 if uid is null then raise exception 'Authentication required'; end if;
 select * into r from english.learning_route_state where user_id=uid and question_id=btrim(p_question_id) and route='fast_track';
 if not found or not r.pending_failure_decision then return jsonb_build_object('ok',false,'reason','no-pending-fast-track-failure'); end if;
 if coalesce(p_add_targeted,false) then return english.route_to_targeted(uid,btrim(p_question_id),'Fast Track Failure','Learner approved Targeted Mastery after Fast Track miss'); end if;
 if r.kept_failure_count>=1 then return english.route_to_targeted(uid,btrim(p_question_id),'Fast Track Failure','Repeated Fast Track miss requires Targeted Mastery'); end if;
 update english.learning_route_state set pending_failure_decision=false,kept_failure_count=kept_failure_count+1,fast_track_status='ready',next_fast_track_check=now()+interval '1 day',last_route_reason='One Fast Track miss kept for confirmation',updated_at=now() where user_id=uid and question_id=btrim(p_question_id);
 perform english.route_event(uid,btrim(p_question_id),'KEEP','fast_track','fast_track','Fast Track Failure','Learner kept one-off miss in Fast Track; confirmation required','{}'::jsonb,null);
 return jsonb_build_object('ok',true,'route','fast_track','status','ready','confirmationRequired',true);
end $$;

create or replace function english.daily_reason(p_user_id uuid,p_question_id text,p_batch_date date)
returns text language sql stable security definer
set search_path=pg_catalog,english,auth as $$
with x as (
 select q,coalesce(s.attempts,0) attempts,coalesce(s.status,'New') state,s.next_review,coalesce(s.mastered,false) mastered,
        coalesce(s.last_marked,false) starred,coalesce(d.difficult,false) difficult,
        exists(select 1 from english.learning_route_state r where r.user_id=p_user_id and r.question_id=q.question_id and r.route='fast_track') fast_track
 from english.questions q
 left join english.question_state s on s.user_id=p_user_id and s.question_id=q.question_id
 left join english.difficult_state d on d.user_id=p_user_id and d.question_id=q.question_id
 where q.question_id=p_question_id
)
select case
 when not (q).active or mastered or fast_track then ''
 when attempts=0 and english.is_genuine_bank_question(q) then 'Controlled New'
 when next_review is null or next_review>((p_batch_date::timestamp+interval '1 day - 1 millisecond') at time zone 'Asia/Kolkata') then ''
 when state='Persistent Weak' then 'Persistent Weak'
 when state='Weak' then 'Weak'
 when state='Fragile' then 'Fragile'
 when difficult then 'Difficult Review'
 when starred then 'Marked Review'
 when state='Learning' then 'Learning'
 else 'Due Spaced Revision' end from x;
$$;

create or replace function public.english_get_revision_hub()
returns jsonb language sql stable security definer
set search_path=pg_catalog,public,english,auth as $$
with c as (
 select q.question_id,coalesce(s.status,'New') status,coalesce(s.attempts,0) attempts,coalesce(s.mastered,false) mastered,
   coalesce(d.difficult,false) difficult,coalesce(s.last_marked,false) starred,s.last_attempt,s.next_review,
   (s.next_review is not null and s.next_review<=(((now() at time zone 'Asia/Kolkata')::date+1)::timestamp at time zone 'Asia/Kolkata')) due
 from english.questions q
 left join english.question_state s on s.user_id=auth.uid() and s.question_id=q.question_id
 left join english.difficult_state d on d.user_id=auth.uid() and d.question_id=q.question_id
 where auth.uid() is not null and q.active and english.question_visible_to_user(auth.uid(),q.question_id)
   and not exists(select 1 from english.learning_route_state r where r.user_id=auth.uid() and r.question_id=q.question_id and r.route='fast_track')
)
select jsonb_build_object(
 'due',count(*) filter(where not mastered and attempts>0 and due),'weak',count(*) filter(where not mastered and status in ('Persistent Weak','Weak','Fragile')),
 'persistentWeak',count(*) filter(where not mastered and status='Persistent Weak'),'difficult',count(*) filter(where not mastered and difficult),
 'starred',count(*) filter(where not mastered and starred),'seenBefore',count(*) filter(where not mastered and attempts>0),
 'mastered',count(*) filter(where mastered),'learning',count(*) filter(where not mastered and status in ('Learning','New'))
) from c;
$$;

create or replace function public.english_get_revision_batch(p_mode text default 'smart',p_count integer default 30)
returns jsonb language plpgsql stable security definer
set search_path=pg_catalog,public,english,auth as $$
declare uid uuid:=auth.uid();m text:=lower(btrim(coalesce(p_mode,'smart')));n integer:=greatest(1,least(100,coalesce(p_count,30)));out jsonb;
begin
 if uid is null then raise exception 'Authentication required'; end if;
 if m not in ('smart','due','weak','recall','difficult','random') then raise exception 'Unknown revision mode: %',p_mode; end if;
 with base as (
  select q.question_id,coalesce(s.status,'New') status,coalesce(s.attempts,0) attempts,coalesce(s.wrong,0) wrong,
    coalesce(d.difficult,false) difficult,coalesce(s.last_marked,false) starred,s.last_attempt,s.next_review,
    (s.next_review is not null and s.next_review<=(((now() at time zone 'Asia/Kolkata')::date+1)::timestamp at time zone 'Asia/Kolkata')) due
  from english.questions q
  left join english.question_state s on s.user_id=uid and s.question_id=q.question_id
  left join english.difficult_state d on d.user_id=uid and d.question_id=q.question_id
  where q.active and not coalesce(s.mastered,false)
    and not exists(select 1 from english.learning_route_state r where r.user_id=uid and r.question_id=q.question_id and r.route='fast_track')
 ), filtered as (
  select * from base where
    (m='smart' and attempts>0 and (due or status in ('Persistent Weak','Weak','Fragile') or difficult)) or
    (m='due' and attempts>0 and due) or (m='weak' and status in ('Persistent Weak','Weak','Fragile')) or
    (m='recall' and attempts>0) or (m='difficult' and difficult) or m='random'
 ), ranked as (
  select *,row_number() over(order by case when m='random' then random() else 0 end,
    case when status='Persistent Weak' and due then 10 when status='Persistent Weak' then 9 when status='Weak' and due then 8 when status='Weak' then 7
         when status='Fragile' and due then 6 when due then 5 when status='Fragile' then 4 when difficult then 3 when status='Learning' then 2 else 1 end desc,
    difficult desc,wrong desc,coalesce(next_review,'infinity'::timestamptz),coalesce(last_attempt,'epoch'::timestamptz),question_id)::int ord
  from filtered
 ), chosen as (select * from ranked order by ord limit n)
 select coalesce(jsonb_agg(english.question_payload(uid,c.question_id)||jsonb_build_object(
   'centralRevisionMode',m,'centralRevisionSignals',english.central_revision_signals(c.status,c.due,c.difficult,c.starred,c.wrong,c.next_review),
   'centralRevisionReason',case when c.status='Persistent Weak' then 'Persistent Weak' when c.status='Weak' then 'Weak' when c.status='Fragile' then 'Fragile'
     when c.due then 'Due Spaced Revision' when c.difficult then 'Difficult' else 'Recall Rotation' end) order by c.ord),'[]'::jsonb) into out from chosen c;
 return out;
end $$;

